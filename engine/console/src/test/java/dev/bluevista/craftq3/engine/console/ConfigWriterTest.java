package dev.bluevista.craftq3.engine.console;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

class ConfigWriterTest {
  private static TestConsole populated() {
    var t = new TestConsole();
    t.cvars().register("name", "player", CvarFlags.ARCHIVE | CvarFlags.USERINFO);
    t.cvars().register("sensitivity", "5", CvarFlags.ARCHIVE);
    t.cvars().register("r_mode", "3", CvarFlags.ARCHIVE | CvarFlags.LATCH);
    t.cvars().register("cl_running", "1", CvarFlags.ROM);
    t.cvars().setUser("r_mode", "4");
    t.bindings().bind(KeyNames.MOUSE1, "+attack");
    t.bindings().bind('a', "+moveleft");
    t.bindings().bind(KeyNames.TAB, "+scores");
    t.bindings().bind(';', "echo semi");
    t.bindings().bind('\\', "toggleconsole");
    return t;
  }

  @Test
  void writesTheOriginalLayoutBindingsByKeyThenCvarsNewestFirst() {
    var result = populated().console.configText();
    assertEquals(
        """
        // generated by quake, do not modify
        unbindall
        bind TAB "+scores"
        bind SEMICOLON "echo semi"
        bind \\ "toggleconsole"
        bind a "+moveleft"
        bind MOUSE1 "+attack"
        seta r_mode "4"
        seta sensitivity "5"
        seta name "player"
        """,
        result.text());
    assertEquals(List.of(), result.skipped());
    assertEquals(result.text(), populated().console.configText().text());
  }

  @Test
  void serverConfigHasNoBindingsSection() {
    var t = new TestConsole(false);
    t.cvars().register("sv_hostname", "noname", CvarFlags.ARCHIVE);
    assertEquals(
        ConfigWriter.HEADER + "\nseta sv_hostname \"noname\"\n", t.console.configText().text());
  }

  // Adapted from legacy GameConfigTest.ambiguousBindingCannotPartiallyReplaceLastGoodConfig:
  // the entry that cannot be represented is left out instead of failing the whole write.
  @Test
  void entriesThatWouldChangeMeaningAreLeftOut() {
    var t = new TestConsole();
    t.bindings().bind('x', "echo \"a; b\"");
    t.bindings().bind('y', "echo fine");
    t.cvars().register("ui_text", "", CvarFlags.ARCHIVE);
    t.cvars().set("ui_text", "\"; unbindall; \"");
    t.cvars().register("ok", "1", CvarFlags.ARCHIVE);
    var result = t.console.configText();
    assertEquals(List.of("bind x", "seta ui_text"), result.skipped());
    assertFalse(result.text().contains("unbindall;"));
    assertTrue(result.text().contains("bind y \"echo fine\"\n"));
    assertTrue(result.text().contains("seta ok \"1\"\n"));
  }

  // Ported from legacy
  // GameConfigTest.homeConfigAndNestedExecOverridePacksAndRestoreBindsAndLatchedValues.
  @Test
  void writtenConfigRestoresCvarsBindingsAndLatchedValuesThroughStartupExec() {
    var first = populated();
    first.run("bind g \"echo hello; echo world\"; unbind a; sensitivity 2.5");
    assertTrue(first.console.writeConfig(Console.CONFIG_FILE));

    var next = new TestConsole();
    next.file(Console.CONFIG_FILE, first.written.get(Console.CONFIG_FILE));
    next.file("autoexec.cfg", "exec nested.cfg");
    next.file("nested.cfg", "seta name \"from nested\"");
    var mode = next.cvars().register("r_mode", "3", CvarFlags.ARCHIVE | CvarFlags.LATCH);
    next.console.queueStartupConfigs(false);
    next.console.frame();
    assertEquals("couldn't exec default.cfg", next.output.getFirst());
    assertEquals(2.5f, next.cvars().value("sensitivity"));
    assertEquals("from nested", next.cvars().string("name"));
    assertTrue(next.cvars().find("sensitivity").orElseThrow().hasAny(CvarFlags.ARCHIVE));
    assertEquals("4", mode.latchedString().orElseThrow());
    next.cvars().applyLatched();
    assertEquals(4, mode.integer());
    assertEquals("", next.bindings().binding('a'));
    assertEquals("+attack", next.bindings().binding(KeyNames.MOUSE1));
    assertEquals("echo hello; echo world", next.bindings().binding('g'));
    assertEquals("toggleconsole", next.bindings().binding('\\'));
    assertEquals("echo semi", next.bindings().binding(';'));
  }

  @Test
  void safeModeSkipsTheArchivedConfig() {
    var t = new TestConsole().file(Console.CONFIG_FILE, "seta x 1").file("autoexec.cfg", "");
    t.console.queueStartupConfigs(true);
    t.console.frame();
    assertTrue(t.cvars().find("x").isEmpty());
    assertEquals(List.of("couldn't exec default.cfg", "execing autoexec.cfg"), t.output);
  }
}
