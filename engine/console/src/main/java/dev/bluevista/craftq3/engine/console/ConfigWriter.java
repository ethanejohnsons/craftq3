package dev.bluevista.craftq3.engine.console;

import dev.bluevista.craftq3.engine.common.log.Log;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Writes a config in the q3config.cfg layout of the original engine ({@code
 * Com_WriteConfigToFile}): the header comment, then {@code unbindall} and one {@code bind} per
 * bound key in key-number order (when bindings are given, i.e. on a client), then one {@code seta}
 * per archived cvar, newest registration first, using the latched value when one is pending.
 *
 * <p>The output is deterministic. The format has no escapes, so a value or binding containing a
 * quote or line break would change meaning when read back (a quoted {@code ;} could even inject a
 * command). Such entries are left out and reported in {@link Result#skipped()}.
 */
public final class ConfigWriter {
  public static final String HEADER = "// generated by quake, do not modify";

  private static final Log LOG = Log.get(ConfigWriter.class);

  /**
   * @param text the config text, each line ending in a newline
   * @param skipped descriptions of the entries that could not be represented
   */
  public record Result(String text, List<String> skipped) {
    public Result {
      skipped = List.copyOf(skipped);
    }
  }

  private ConfigWriter() {}

  /** A config with cvars only (a dedicated server has no key bindings). */
  public static Result write(CvarTable cvars) {
    return write(cvars, null);
  }

  /**
   * @param bindings the client's key bindings, or null to omit the bindings section
   */
  public static Result write(CvarTable cvars, KeyBindings bindings) {
    StringBuilder text = new StringBuilder(HEADER).append('\n');
    List<String> skipped = new ArrayList<>();
    if (bindings != null) {
      text.append("unbindall\n");
      for (Map.Entry<Integer, String> entry : bindings.all().entrySet()) {
        String name = KeyNames.toName(entry.getKey());
        if (!representable(entry.getValue())) {
          skipped.add("bind " + name);
          continue;
        }
        text.append("bind ").append(name).append(" \"").append(entry.getValue()).append("\"\n");
      }
    }
    List<Cvar> all = cvars.all();
    for (int i = all.size() - 1; i >= 0; i--) {
      Cvar cvar = all.get(i);
      if (!cvar.hasAny(CvarFlags.ARCHIVE)) continue;
      String value = cvar.latchedString().orElse(cvar.string());
      if (!representable(value) || !representable(cvar.name())) {
        skipped.add("seta " + cvar.name());
        continue;
      }
      text.append("seta ").append(cvar.name()).append(" \"").append(value).append("\"\n");
    }
    for (String entry : skipped)
      LOG.warnOnce(
          "unrepresentable:" + entry, "Left out of config (quote or line break): " + entry);
    return new Result(text.toString(), skipped);
  }

  private static boolean representable(String text) {
    for (int i = 0; i < text.length(); i++) {
      char c = text.charAt(i);
      if (c == '"' || c == '\n' || c == '\r' || c == 0) return false;
    }
    return true;
  }
}
