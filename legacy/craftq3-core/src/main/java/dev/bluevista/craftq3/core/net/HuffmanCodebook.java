  private static final int[] DECODE = makeLookup();

  private HuffmanCodebook() {}

  static int code(int symbol) {
    return CODES[symbol];
  }

  static int length(int code) {
    return 31 - Integer.numberOfLeadingZeros(code);
  }

  static int decode(int window) {
    return DECODE[window];
  }

  private static int[] makeLookup() {
    int[] table = new int[2048];
    for (int symbol = 0; symbol < CODES.length; symbol++) {
      int size = length(CODES[symbol]);
      int bits = CODES[symbol] ^ (1 << size);
      for (int suffix = 0; suffix < 1 << (11 - size); suffix++) {
        int index = bits | (suffix << size);
        if (table[index] != 0)
          throw new ExceptionInInitializerError("Non-prefix-free network codes");
        table[index] = (size << 8) | symbol;
      }
    }
    return table;
  }
